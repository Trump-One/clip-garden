// Electron 44 uses the asynchronous ClipboardItem/Blob clipboard API.
function createClipboardAdapter({ clipboard, ClipboardItem, nativeImage }) {
  return {
    async read() {
      const entries = await clipboard.read();
      const types = entries.flatMap(item => item.types);
      if (types.some(t => /concealed|transient|password|org\.nspasteboard\.AutoGeneratedType/i.test(t))) return null;
      for (const mime of ['image/png', 'image/jpeg', 'image/tiff']) {
        const entry = entries.find(item => item.types.includes(mime));
        if (!entry) continue;
        const blob = await entry.getType(mime);
        if (blob.size > 20 * 1024 * 1024) return null;
        const image = nativeImage.createFromBuffer(Buffer.from(await blob.arrayBuffer()));
        if (image.isEmpty()) return null;
        const size = image.getSize(); if (size.width * size.height > 30000000) return null;
        const png = image.toPNG(); if (png.length > 20 * 1024 * 1024) return null;
        return { kind: 'image', content: 'data:image/png;base64,' + png.toString('base64') };
      }
      const text = await clipboard.readText();
      return text && Buffer.byteLength(text) <= 2 * 1024 * 1024 ? { kind: 'text', content: text } : null;
    },
    async write(item) {
      if (item.kind === 'image') {
        const bytes = Buffer.from(item.content.slice(item.content.indexOf(',') + 1), 'base64');
        await clipboard.write([new ClipboardItem({ 'image/png': new Blob([bytes], { type: 'image/png' }) })]);
      } else await clipboard.writeText(item.content);
    }
  };
}
module.exports = { createClipboardAdapter };
